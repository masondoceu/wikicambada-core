let activeLanguage = 'pt-BR'

export function setInterfaceLanguage(language) {
  activeLanguage = language === 'en' ? 'en' : 'pt-BR'
  document.documentElement.lang = activeLanguage
  return activeLanguage
}

export function interfaceLanguage() {
  return activeLanguage
}

export function interfaceLocale() {
  return activeLanguage === 'en' ? 'en-US' : 'pt-BR'
}

export function t(key, values = {}) {
  return translate(activeLanguage, key, values)
}

export function translate(language, key, values = {}) {
  const template = messages[language]?.[key] ?? messages['pt-BR']?.[key] ?? key
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{{${name}}}`, String(value ?? '')), template)
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = t(element.dataset.i18n)
  })
  root.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder))
  })
  root.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel))
  })
  root.querySelectorAll('[data-i18n-title]').forEach(element => {
    element.setAttribute('title', t(element.dataset.i18nTitle))
  })
}
